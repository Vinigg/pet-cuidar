CREATE TABLE veterinarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    especialidade VARCHAR(255),
    versao BIGINT NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE horarios_atendimento_veterinario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veterinario_id BIGINT NOT NULL REFERENCES veterinarios(id),
    dia_semana VARCHAR(255) NOT NULL CHECK (dia_semana IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    hora_inicio VARCHAR(5) NOT NULL,
    hora_fim VARCHAR(5) NOT NULL,
    CHECK (hora_inicio < hora_fim)
);
CREATE INDEX idx_horarios_veterinario ON horarios_atendimento_veterinario(veterinario_id);

CREATE TABLE bloqueios_agenda_veterinario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veterinario_id BIGINT NOT NULL REFERENCES veterinarios(id),
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    motivo VARCHAR(255)
);
CREATE INDEX idx_bloqueios_veterinario_periodo ON bloqueios_agenda_veterinario(veterinario_id, inicio, fim);

CREATE TABLE tutores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    telefone VARCHAR(255),
    cpf VARCHAR(255) UNIQUE,
    email_normalizado TEXT
);
CREATE INDEX idx_tutores_email_normalizado ON tutores(email_normalizado);

CREATE TABLE pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id BIGINT NOT NULL REFERENCES tutores(id),
    nome VARCHAR(255) NOT NULL,
    especie VARCHAR(255),
    idade INTEGER,
    alergias_criticas VARCHAR(1000)
);
CREATE INDEX idx_pets_tutor ON pets(tutor_id);

CREATE TABLE consultas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL REFERENCES pets(id),
    veterinario_id BIGINT NOT NULL REFERENCES veterinarios(id),
    data_hora TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AGENDADA'
        CHECK (status IN ('AGENDADA', 'CONFIRMADA', 'REALIZADA', 'CANCELADA', 'NAO_COMPARECEU'))
);
CREATE INDEX idx_consultas_pet ON consultas(pet_id);
CREATE INDEX idx_consultas_vet_data ON consultas(veterinario_id, data_hora);

CREATE TABLE historico_atendimentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT NOT NULL REFERENCES pets(id),
    consulta_id BIGINT REFERENCES consultas(id),
    descricao VARCHAR(2000),
    resumo_ia VARCHAR(1000),
    data TIMESTAMP NOT NULL,
    veterinario_id BIGINT REFERENCES veterinarios(id),
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    veterinario_criacao_id BIGINT REFERENCES veterinarios(id),
    veterinario_atualizacao_id BIGINT REFERENCES veterinarios(id),
    versao BIGINT DEFAULT 0
);
CREATE INDEX idx_historico_pet ON historico_atendimentos(pet_id);
CREATE INDEX idx_historico_vet ON historico_atendimentos(veterinario_id);
CREATE INDEX idx_historico_vet_criacao ON historico_atendimentos(veterinario_criacao_id);
CREATE INDEX idx_historico_vet_atualizacao ON historico_atendimentos(veterinario_atualizacao_id);
CREATE INDEX idx_historico_data_atualizacao ON historico_atendimentos(data_atualizacao);

CREATE TABLE lembretes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id BIGINT NOT NULL UNIQUE REFERENCES consultas(id),
    canal VARCHAR(255) NOT NULL DEFAULT 'EMAIL',
    texto_gerado_ia VARCHAR(1000),
    texto_validado VARCHAR(1000),
    status_envio VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status_envio IN ('PENDENTE', 'ENVIADO', 'FALHOU')),
    data_envio TIMESTAMP,
    tentativas INTEGER DEFAULT 0,
    ultimo_erro VARCHAR(1000),
    data_ultima_tentativa TIMESTAMP,
    usou_fallback BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE predicoes_no_show (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id BIGINT NOT NULL UNIQUE REFERENCES consultas(id),
    score_cru NUMERIC CHECK (score_cru BETWEEN 0 AND 1),
    score_usado NUMERIC CHECK (score_usado BETWEEN 0 AND 1),
    usou_fallback BOOLEAN NOT NULL DEFAULT FALSE,
    motivo VARCHAR(500),
    data_calculo TIMESTAMP NOT NULL
);

CREATE TABLE contas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    nome TEXT NOT NULL,
    perfil TEXT NOT NULL CHECK (perfil IN ('TUTOR', 'VETERINARIO', 'COLABORADOR', 'ADMIN')),
    tutor_id BIGINT UNIQUE REFERENCES tutores(id),
    veterinario_id BIGINT UNIQUE REFERENCES veterinarios(id),
    CHECK ((perfil = 'TUTOR') = (tutor_id IS NOT NULL)),
    CHECK ((perfil = 'VETERINARIO') = (veterinario_id IS NOT NULL))
);

CREATE TABLE desafios_email (
    email TEXT NOT NULL,
    finalidade TEXT NOT NULL CHECK (finalidade IN ('LOGIN', 'CADASTRO')),
    digest TEXT,
    criado_em BIGINT NOT NULL,
    expira_em BIGINT NOT NULL,
    tentativas INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (email, finalidade)
);
CREATE INDEX idx_desafios_email_expira ON desafios_email(expira_em);

CREATE TABLE credenciais_auth (
    digest TEXT PRIMARY KEY,
    conta_id BIGINT REFERENCES contas(id),
    email TEXT,
    expira_em BIGINT NOT NULL,
    CHECK ((conta_id IS NOT NULL) <> (email IS NOT NULL))
);
CREATE INDEX idx_credenciais_auth_expira ON credenciais_auth(expira_em);
CREATE INDEX idx_credenciais_auth_conta ON credenciais_auth(conta_id);
